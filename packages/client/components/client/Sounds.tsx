export type SoundKey = keyof TypeSounds;

/**
 * The single sound registry: every event and its asset. Event playback and
 * the settings previews both resolve through this map, so a preview always
 * plays exactly what the event plays.
 *
 * Except `message`, the assets are generated by scripts/generate-sounds.mjs.
 */
export const SOUND_ASSETS: Record<SoundKey, string> = {
  deafen: deafenSound,
  message: messageSound,
  mute: muteSound,
  ringtoneIncoming: ringtoneIncomingSound,
  ringtoneOutgoing: ringtoneOutgoingSound,
  streamEnd: streamEndSound,
  streamStart: streamStartSound,
  streamViewerJoin: streamViewerJoinSound,
  streamViewerLeave: streamViewerLeaveSound,
  undeafen: undeafenSound,
  unmute: unmuteSound,
  userJoinVoice: userJoinVoiceSound,
  userLeaveVoice: userLeaveVoiceSound,
  userMoved: userMovedSound,
};

/**
 * Outcome of starting a sound. `ok` means the browser accepted playback;
 * it does not prove anything was audible (output device, OS volume).
 */
export type PlaybackResult =
  | { ok: true }
  | {
      ok: false;
      /**
       * blocked: autoplay policy (no user gesture yet)
       * failed: the asset could not be loaded or decoded
       * unsupported: the output device could not be selected
       */
      reason: "blocked" | "failed" | "unsupported";
      error: unknown;
    };

/**
 * A controller class for making sure sounds are managed in one place and to prevent undesirable sound overlaps
 */
export class SoundController {
  readonly soundState: Sounds;
  readonly voiceState?: Voice;

  node?: HTMLAudioElement;

  /**
   * The settings preview currently playing; a new preview replaces it
   */
  previewNode?: HTMLAudioElement;

  lastPlayedSound?: SoundKey;

  constructor(soundState: Sounds, voiceState?: Voice) {
    this.soundState = soundState;
    this.voiceState = voiceState;

    this.isPlaying = this.isPlaying.bind(this);
    this.canPlay = this.canPlay.bind(this);
    this.playSound = this.playSound.bind(this);
    this.preview = this.preview.bind(this);
  }

  /**
   * Get whether a sound is currently being played by the sound controller
   *
   * @returns Whether a sound is currently playing
   */
  isPlaying(): boolean {
    return !!this.node && !this.node.paused && !this.node.ended;
  }

  /**
   * Get whether a sound can be played right now
   *
   * @param newSound Sound to check for playability
   * @returns Whether the sound passed is playable currently
   */
  canPlay(newSound: SoundKey): boolean {
    // Never let a sound turned off play
    if (!this.soundState.enabled(newSound)) {
      return false;
    }

    // Always let the sound play if nothing is currently playing
    if (!this.isPlaying()) {
      return true;
    }

    // If there are any cases where you don't want sound collisions, put them here.
    // None for now.
    return true;
  }

  /**
   * Create an audio element for a sound, routed to the speaker chosen in
   * Voice & Video so interface sounds and call audio come out of the same
   * device
   */
  private async createNode(sound: SoundKey) {
    const node = new Audio(SOUND_ASSETS[sound]);
    node.preload = "auto";

    const deviceId = this.voiceState?.preferredAudioOutputDevice;
    if (deviceId && deviceId !== "default" && "setSinkId" in node) {
      try {
        await (
          node as HTMLAudioElement & { setSinkId(id: string): Promise<void> }
        ).setSinkId(deviceId);
      } catch (error) {
        // device unplugged or not permitted: fall back to the system default
        console.warn(
          `[sounds] could not use the selected speaker for "${sound}", using the default device`,
          error,
        );
      }
    }

    return node;
  }

  /**
   * Start playback and report the outcome instead of swallowing it
   */
  private async start(
    node: HTMLAudioElement,
    sound: SoundKey,
  ): Promise<PlaybackResult> {
    try {
      await node.play();
      return { ok: true };
    } catch (error) {
      const blocked =
        error instanceof DOMException && error.name === "NotAllowedError";
      console.warn(`[sounds] "${sound}" did not play`, error);
      return { ok: false, reason: blocked ? "blocked" : "failed", error };
    }
  }

  /**
   * Play a sound, following the rules of sound playability unless force is true
   *
   * @param sound The sound to play
   * @param force Bypass canPlay check
   * @returns Whether the sound was started
   */
  playSound(sound: SoundKey, force?: boolean): boolean {
    if (!force && !this.canPlay(sound)) {
      return false;
    }

    this.lastPlayedSound = sound;
    this.createNode(sound).then((node) => {
      this.node = node;
      return this.start(node, sound);
    });
    return true;
  }

  /**
   * Preview a sound from settings: plays even if the event is switched off
   * and replaces any preview still playing, so repeated clicks don't stack
   *
   * @param sound The sound to preview
   * @returns Playback outcome
   */
  async preview(sound: SoundKey): Promise<PlaybackResult> {
    if (this.previewNode) {
      this.previewNode.pause();
      this.previewNode.currentTime = 0;
    }

    const node = await this.createNode(sound);
    this.previewNode = node;
    this.lastPlayedSound = sound;
    return this.start(node, sound);
  }
}

const soundContext = createContext(null! as SoundController);

export function SoundContext(props: { children: JSXElement }) {
  const { sounds, voice } = useState();

  const controller = new SoundController(sounds, voice);

  return (
    <soundContext.Provider value={controller}>
      {props.children}
    </soundContext.Provider>
  );
}

export function useSound(): SoundController {
  return useContext(soundContext);
}
