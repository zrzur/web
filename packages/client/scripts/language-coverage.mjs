/**
 * Measures how much of each Lingui catalog is translated and writes
 * components/i18n/coverage.ts, which the language picker uses to group
 * languages honestly (complete / partial / in progress).
 *
 *   node scripts/language-coverage.mjs
 *
 * Counts non-obsolete msgids with a non-empty msgstr. Re-run after
 * `lingui extract` or catalog updates.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalogs = join(root, "components", "i18n", "catalogs");

const coverage = {};
for (const lang of readdirSync(catalogs).sort()) {
  const file = join(catalogs, lang, "messages.po");
  if (!existsSync(file)) continue;
  const source = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  let total = 0;
  let done = 0;
  for (const block of source.split(/\n\s*\n/)) {
    if (/^#~/m.test(block)) continue;
    const m = block.match(/^msgid ((?:".*"\n?)+)msgstr ((?:".*"\n?)+)/m);
    if (!m) continue;
    if (m[1].replace(/"\n"/g, "").trim() === '""') continue; // header
    total++;
    if (m[2].replace(/"\n"/g, "").trim() !== '""') done++;
  }
  coverage[lang] = total ? Math.floor((100 * done) / total) : 0;
}

const body = Object.entries(coverage)
  .map(([lang, pct]) => `  ${JSON.stringify(lang)}: ${pct},`)
  .join("\n");

writeFileSync(
  join(root, "components", "i18n", "coverage.ts"),
  `// Generated by scripts/language-coverage.mjs, do not edit by hand.
// Percentage of catalog messages translated, per Lingui catalog id.
export const LANGUAGE_COVERAGE: Record<string, number> = {
${body}
};
`,
);
console.log(coverage);
